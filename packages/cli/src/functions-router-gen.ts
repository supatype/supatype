/**
 * Generates a Deno router entrypoint so `deno run` (optionally `deno run --watch` in dev)
 * can serve multiple handlers (same routing contract as `supatype functions serve`).
 */
import {
  basename,
  join,
  relative,
  dirname,
  resolve as pathResolve,
} from "node:path"
import { chmodSync, existsSync, readdirSync, rmSync, statSync, mkdirSync, writeFileSync } from "node:fs"
import { FUNCTION_NAME_RULE, isFunctionName } from "@supatype/shared"
import { fatalError } from "./ui/fatal.js"
import { uniqueFileToken } from "./unique-file-token.js"
import { pidAlive } from "./parent-watch.js"
import { createHash } from "node:crypto"
import { hostname } from "node:os"

export interface DiscoveredFunctionRoute {
  name: string
  entrypoint: string
  /** The `{name}/` folder, or the `{name}.ts` file. */
  path: string
}

/**
 * A function the control plane would refuse by its name. Named here, where the folder is found,
 * so `dev`, `functions serve` and `functions deploy` say so before anything runs or is sent.
 */
export class InvalidFunctionNameError extends Error {
  override readonly name = "InvalidFunctionNameError"
}

/**
 * Why `name` is not a function name, or undefined when it is one. `entry` is what holds it in the
 * functions directory (`sendEmail/`, `Webhook.ts`).
 */
export function functionNameProblem(name: string, entry: string = name): string | undefined {
  if (isFunctionName(name)) return undefined
  const suggestion = suggestedFunctionName(name)
  const example = suggestion === undefined ? "" : ` (for example "${suggestion}")`
  return `"${entry}" is not a valid function name: ${FUNCTION_NAME_RULE}${example}.`
}

/** `sendEmail` as `send-email`: what a name the rule refuses most likely meant, if anything. */
function suggestedFunctionName(name: string): string | undefined {
  const kebab = name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/^[-_]+/, "")
  return isFunctionName(kebab) ? kebab : undefined
}

/** The function `entry` in `functionsDir` holds, or undefined for anything that is not one. */
function functionAt(functionsDir: string, entry: string): DiscoveredFunctionRoute | undefined {
  if (entry.startsWith("_") || entry.startsWith(".")) return undefined
  const fullPath = join(functionsDir, entry)
  if (statSync(fullPath).isDirectory()) {
    const indexTs = join(fullPath, "index.ts")
    return existsSync(indexTs) ? { name: entry, entrypoint: indexTs, path: fullPath } : undefined
  }
  if (!entry.endsWith(".ts") || entry.endsWith(".d.ts")) return undefined
  return { name: basename(entry, ".ts"), entrypoint: fullPath, path: fullPath }
}

/**
 * Discover *.ts handlers and `{name}/index.ts` dirs; skips `_shared`, dotfiles. Throws
 * {@link InvalidFunctionNameError} naming every one the control plane would refuse.
 */
export function discoverTsFunctionsInDir(functionsDir: string): DiscoveredFunctionRoute[] {
  if (!existsSync(functionsDir)) return []

  const found = readdirSync(functionsDir)
    .map((entry) => functionAt(functionsDir, entry))
    .filter((fn): fn is DiscoveredFunctionRoute => fn !== undefined)
  const problems = found
    .map((fn) => functionNameProblem(fn.name, fn.path === fn.entrypoint ? basename(fn.path) : `${fn.name}/`))
    .filter((problem): problem is string => problem !== undefined)
  if (problems.length > 0) {
    throw new InvalidFunctionNameError(
      [`The control plane would refuse ${problems.length} function(s) in ${functionsDir}:`, ...problems.map((p) => `  ${p}`)].join("\n"),
    )
  }
  return found.sort((a, b) => a.name.localeCompare(b.name))
}

/** {@link discoverTsFunctionsInDir}, ending the command with why when a name would be refused. */
export function discoverFunctionsOrExit(functionsDir: string): DiscoveredFunctionRoute[] {
  try {
    return discoverTsFunctionsInDir(functionsDir)
  } catch (err: unknown) {
    if (err instanceof InvalidFunctionNameError) fatalError(err.message)
    throw err
  }
}

function importSpecFromRouter(routerFilePath: string, entrypoint: string): string {
  const rel = relative(dirname(routerFilePath), entrypoint).replace(/\\/g, "/")
  if (!rel.startsWith(".")) return `./${rel}`
  return rel
}

/**
 * Router source rooted at routerFilePath (defines import paths). `serviceRoleKeyFile` is the file
 * {@link writeServiceRoleKeyFile} wrote the service-role key to; without one no function is given it.
 */
export function generateFunctionsRouterSource(
  routerFilePath: string,
  fns: ReadonlyArray<Pick<DiscoveredFunctionRoute, "name" | "entrypoint">>,
  serviceRoleKeyFile?: string,
): string {
  // Dynamic imports, evaluated in order once the key is withheld; see the comment in the router.
  const routes = fns.map(
    (fn) =>
      `  "${fn.name}": await loadHandler("${fn.name}", () => import("${importSpecFromRouter(routerFilePath, fn.entrypoint)}")),`,
  )

  return `// Auto-generated: do not edit (regenerated by supatype dev / functions serve)
import { AsyncLocalStorage } from "node:async_hooks"

// The service-role key comes out of the environment before any handler is imported, as the deployed
// worker does. A handler's module body runs when it is imported, so a key still in Deno.env then is a
// key every function can copy and keep. The handlers below are imported dynamically for this reason:
// a static import is hoisted above every statement and would run before this line.
//
// The key itself is read from the file the CLI wrote it to, named here rather than in the
// environment. Native dev and functions serve run this under deno run --watch, which reloads it by
// evaluating it again in the same process, whose environment an earlier evaluation already took the
// key out of; a path kept there would have to be taken out the same way. The file is still there
// however that evaluation ended, so nothing has to be put back. The server passes its own
// SUPATYPE_SERVICE_ROLE_KEY to this process too, so that goes all the same.
const serviceRoleKeyFile = ${JSON.stringify(serviceRoleKeyFile ?? "")}
Deno.env.delete("SUPATYPE_SERVICE_ROLE_KEY")

async function readServiceRoleKey(path: string): Promise<string> {
  if (!path) return ""
  try {
    return (await Deno.readTextFile(path)).trim()
  } catch (err) {
    console.error("[supatype] no function is given the service-role key: could not read " + path
      + " (" + (err instanceof Error ? err.message : String(err)) + ")")
    return ""
  }
}

const serviceRoleKey = await readServiceRoleKey(serviceRoleKeyFile)

// functions.serviceRole from the config. A public function gets the key only when it is listed
// here; a hook, which only the API server calls, always does.
const serviceRoleRoutes = new Set(
  (Deno.env.get("SUPATYPE_SERVICE_ROLE_ROUTES") ?? "").split(",").map((r) => r.trim()).filter((r) => r !== ""),
)

function serviceRoleGranted(route: string): boolean {
  return route.startsWith("hooks/") || serviceRoleRoutes.has(route)
}

/**
 * What a function is told about the call it is serving.
 *
 * Passed as the second argument rather than injected into the process environment, so
 * invocations do not have to
 * be serialised to keep one call's configuration out of another's.
 */
interface FunctionContext {
  readonly executionId: string
  readonly functionName: string
  /** For calling the API from inside the function. */
  readonly url: string
  /** The project's public address, for links you give to people. */
  readonly publicUrl: string
  readonly anonKey: string
  readonly serviceRoleKey?: string
  readonly dbUrl?: string
  readonly region: string
  readonly env: Readonly<Record<string, string>>
}

type Handler = (req: Request, ctx: FunctionContext) => Response | Promise<Response>

/** The module's default export, else its named "handler" export, as the deployed worker takes them. */
function exportedHandler(mod: Record<string, unknown>): Handler {
  const handler = mod.default ?? mod.handler
  if (typeof handler !== "function") {
    throw new Error('it has neither a default export nor a named "handler" export')
  }
  // A boundary: that it is a function is what can be checked; its signature is the author's contract.
  return handler as Handler
}

/** Terminal escape codes. Deno colours a missing module's location in its message, piped or not. */
const TERMINAL_ESCAPES = /\\u001b\\[[0-9;?]*[A-Za-z]/g

/**
 * The handler \`load\` imports, or, when it cannot be loaded, one that answers its route with a 500
 * saying why. One module that failed to import, or exported no handler, used to stop the router
 * starting, so every function answered 502 where only that one was broken. The message goes out
 * as JSON, so the escape codes come out of it: a client has no terminal to colour.
 */
async function loadHandler(name: string, load: () => Promise<Record<string, unknown>>): Promise<Handler> {
  try {
    return exportedHandler(await load())
  } catch (err) {
    const reason = (err instanceof Error ? err.message : String(err)).replace(TERMINAL_ESCAPES, "")
    const message = 'Function "' + name + '" failed to load: ' + reason
    console.error("[supatype] " + message)
    const body = JSON.stringify({ error: "function_load_failed", message })
    return () => new Response(body, { status: 500, headers: { "Content-Type": "application/json" } })
  }
}

const handlers: Record<string, Handler> = {
${routes.join("\n")}
}

const port = parseInt(Deno.env.get("PORT") ?? "8001", 10)
// This machine only, unless asked: on every address, other machines on the network reached it.
const hostname = Deno.env.get("SUPATYPE_FUNCTIONS_HOST") ?? "127.0.0.1"
const functionsDir = Deno.env.get("SUPATYPE_DENO_FUNCTIONS_DIR") ?? ""
const normalizedFunctionsDir = functionsDir.endsWith("/") ? functionsDir.slice(0, -1) : functionsDir
const sharedEnvPath = Deno.env.get("SUPATYPE_SHARED_ENV_FILE")
  ?? (normalizedFunctionsDir ? normalizedFunctionsDir + "/.env.local" : "")

// Nothing per-invocation is written to Deno.env, so invocations run concurrently.
//
// This used to hold a lock across the whole handler because the config was delivered by mutating
// the process environment, which is global: two concurrent calls would read each other's values.
// The lock made the router run one invocation at a time, so a function waiting on a slow API
// blocked every other function locally, and the deployed worker had the same lock, so local
// behaved exactly like production and the serialisation was invisible.
const invocationStore = new AsyncLocalStorage<{ executionId: string; functionName: string }>()

const realConsole = {
  debug: console.debug.bind(console),
  info: console.info.bind(console),
  log: console.log.bind(console),
  warn: console.warn.bind(console),
  error: console.error.bind(console),
}

function projectRef(): string {
  return (Deno.env.get("SUPATYPE_PROJECT_REF") ?? "").trim() || "unknown"
}

function emit(level: string, message: string, extra: Record<string, unknown> = {}): void {
  const current = invocationStore.getStore()
  const line = {
    timestamp: new Date().toISOString(),
    level,
    service: "functions-worker",
    project_ref: projectRef(),
    ...(current ? { request_id: current.executionId, function: current.functionName } : {}),
    message,
    ...extra,
  }
  const write = level === "error" ? realConsole.error : realConsole.log
  write(JSON.stringify(line))
}

function formatArg(value: unknown): string {
  if (typeof value === "string") return value
  if (value instanceof Error) return value.stack ?? value.name + ": " + value.message
  try {
    return JSON.stringify(value) ?? String(value)
  } catch {
    return String(value)
  }
}

// A function's own console output, structured and attributed to the call that wrote it. Captured
// before any handler runs so nothing it logs escapes unlabelled.
for (const [method, level] of [["debug", "debug"], ["info", "info"], ["log", "info"], ["warn", "warn"], ["error", "error"]] as const) {
  console[method] = (...args: unknown[]): void => {
    emit(level, args.map(formatArg).join(" "))
  }
}

async function readEnvFile(path: string): Promise<Record<string, string>> {
  if (!path) return {}
  try {
    const text = await Deno.readTextFile(path)
    const out: Record<string, string> = {}
    for (const raw of text.split("\\n")) {
      const line = raw.trim()
      if (!line || line.startsWith("#")) continue
      const eq = line.indexOf("=")
      if (eq <= 0) continue
      const key = line.slice(0, eq).trim()
      let value = line.slice(eq + 1).trim()
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1)
      }
      out[key] = value
    }
    return out
  } catch {
    return {}
  }
}

async function scopedEnvForFunction(fnName: string): Promise<Record<string, string>> {
  const shared = await readEnvFile(sharedEnvPath)
  if (!normalizedFunctionsDir) return shared
  const fnVars = await readEnvFile(normalizedFunctionsDir + "/.env." + fnName + ".local")
  return { ...shared, ...fnVars }
}

// Once, at start, as the deployed worker does: the value never differs between calls, and an unset
// variable is worth one warning rather than one per call.
function resolvePublicUrl(): string {
  const configured = (Deno.env.get("SUPATYPE_PUBLIC_URL") ?? "").trim()
  if (configured !== "") return configured
  const internal = Deno.env.get("SUPATYPE_URL") ?? ""
  emit("warn", "SUPATYPE_PUBLIC_URL is not set, so ctx.publicUrl falls back to ctx.url ("
    + (internal || "unset") + "), which may be an address only this stack can reach")
  return internal
}

const publicUrl = resolvePublicUrl()

Deno.serve({
  hostname,
  port,
  onListen: ({ hostname, port: bound }) => {
    emit("info", "functions router listening on http://" + hostname + ":" + bound)
  },
}, async (req: Request): Promise<Response> => {
  const url = new URL(req.url)
  const pathParts = url.pathname
    .replace(/^\\/functions\\/v1\\/?/, "")
    .split("/")
    .filter(Boolean)
  const fnName = pathParts[0] ?? ""

  if (!fnName || !handlers[fnName]) {
    return new Response(JSON.stringify({
      error: "not_found",
      message: fnName ? 'Function "' + fnName + '" not found' : "No function specified",
      available: Object.keys(handlers),
    }), { status: 404, headers: { "Content-Type": "application/json" } })
  }

  const anonKey = Deno.env.get("SUPATYPE_ANON_KEY") ?? ""
  const dbUrl = Deno.env.get("SUPATYPE_DB_URL") ?? Deno.env.get("DATABASE_URL")
  const context: FunctionContext = {
    executionId: crypto.randomUUID(),
    functionName: fnName,
    url: Deno.env.get("SUPATYPE_URL") ?? "",
    publicUrl,
    anonKey,
    ...(serviceRoleKey && serviceRoleGranted(fnName) ? { serviceRoleKey } : {}),
    ...(dbUrl ? { dbUrl } : {}),
    region: Deno.env.get("SUPATYPE_REGION") ?? "local",
    env: await scopedEnvForFunction(fnName),
  }

  const start = performance.now()

  try {
    const response = await invocationStore.run(
      { executionId: context.executionId, functionName: fnName },
      async () => handlers[fnName]!(req, context),
    )
    // After the invocation's context has ended, so it names its function itself: the server keeps a
    // function's own log by this field.
    emit("info", req.method + " /functions/v1/" + fnName + " -> " + response.status, {
      request_id: context.executionId,
      function: fnName,
      status: response.status,
      duration_ms: Number((performance.now() - start).toFixed(1)),
    })
    return response
  } catch (err) {
    // Plain, as a load failure's: the message goes out as JSON, and a module a handler imports
    // late fails with the same coloured text.
    const message = err instanceof Error ? err.message.replace(TERMINAL_ESCAPES, "") : "Unknown error"
    emit("error", message, {
      request_id: context.executionId,
      function: fnName,
      status: 500,
      duration_ms: Number((performance.now() - start).toFixed(1)),
    })
    return new Response(JSON.stringify({ error: "function_error", message }), {
      status: 500,
      headers: { "Content-Type": "application/json" },
    })
  }
})
`
}

/** Where native dev keeps the service-role key for the router it runs: in `.supatype/` under cwd. */
export function devServiceRoleKeyPath(cwd: string): string {
  return join(pathResolve(cwd, ".supatype"), "service-role-key")
}

/**
 * Writes the service-role key to `keyPath`, readable by its owner only where the platform has such
 * permissions. The router reads the key from there on every evaluation rather than from its
 * environment, which an earlier `--watch` evaluation has already taken the key out of. It belongs
 * in `.supatype/`, the CLI's own directory, which `init` adds to `.gitignore`.
 */
export function writeServiceRoleKeyFile(keyPath: string, serviceRoleKey: string): void {
  mkdirSync(dirname(keyPath), { recursive: true, mode: 0o700 })
  writeFileSync(keyPath, serviceRoleKey, { encoding: "utf8", mode: 0o600 })
  // The mode above applies only to a file it creates; one left by an earlier run keeps its own.
  chmodSync(keyPath, 0o600)
}

/**
 * Removes `path` when this process exits. A process killed outright leaves it behind, which
 * {@link sweepStaleServeFiles} clears for `functions serve`. A file that cannot go (held open on
 * Windows) stays rather than throwing past the exit listeners after this one.
 */
export function removeOnExit(path: string): void {
  process.once("exit", () => {
    try {
      rmSync(path, { force: true })
    } catch {
      // Nothing is left to report to: the process is exiting.
    }
  })
}

/** The router and key file one `functions serve` writes. */
export interface FunctionsServeFiles {
  routerPath: string
  keyPath: string
}

/**
 * Which machine and system a serve file was written on. A pid is only meaningful there: WSL and
 * Windows, or a container, can serve one mounted project, and each would read the other's live
 * pids as dead.
 */
const SERVE_HOST_TAG = createHash("sha256").update(`${process.platform}:${hostname()}`).digest("hex").slice(0, 8)

/**
 * Where one `functions serve` keeps its router and key: files of its own, since each removes them
 * when it stops while another may still be serving the same project. The name carries this host's
 * tag and, inside `token`, the pid {@link sweepStaleServeFiles} reads back.
 */
export function functionsServeFiles(
  cwd: string,
  functionsDir: string,
  token: string = uniqueFileToken(),
): FunctionsServeFiles {
  const name = `${SERVE_HOST_TAG}-${token}`
  return {
    routerPath: join(functionsDir, `.serve-router-${name}.ts`),
    keyPath: join(pathResolve(cwd, ".supatype"), `functions-serve-key-${name}`),
  }
}

/** A serve file's name: `<host tag>-<time>-<pid>-<uuid>`, capturing the tag and the pid. */
const SERVE_FILE_NAME = /^(?:\.serve-router-|functions-serve-key-)([0-9a-f]{8})-\d+-(\d+)-[0-9a-f-]+(?:\.ts)?$/

/**
 * Removes the router and key files of this host's serves whose process is gone. One killed
 * outright runs no exit listener, and no later serve shares its file names, so its key would stay
 * on disk for good. A file that cannot go (held open on Windows) is left for a later sweep.
 */
export function sweepStaleServeFiles(cwd: string, functionsDir: string): void {
  for (const dir of [functionsDir, pathResolve(cwd, ".supatype")]) {
    const names = existsSync(dir) ? readdirSync(dir) : []
    for (const name of names) {
      const match = SERVE_FILE_NAME.exec(name)
      if (match?.[1] !== SERVE_HOST_TAG || pidAlive(Number(match[2]))) continue
      try {
        rmSync(join(dir, name), { force: true })
      } catch {
        // Left for the next serve to sweep.
      }
    }
  }
}

/**
 * {@link writeServiceRoleKeyFile}, removing the file again when this process exits, so the key is
 * on disk only while something that uses it is running.
 */
export function writeServiceRoleKeyFileUntilExit(keyPath: string, serviceRoleKey: string): void {
  writeServiceRoleKeyFile(keyPath, serviceRoleKey)
  removeOnExit(keyPath)
}

/**
 * Writes `.supatype/functions-router.ts` under project cwd. Returns absolute path or null if no handlers.
 * Pass `routes` when callers already scanned the dir to avoid duplicate I/O.
 */
export function writeDevFunctionsRouter(
  cwd: string,
  functionsDir: string,
  routes?: DiscoveredFunctionRoute[],
): string | null {
  const fns = routes ?? discoverTsFunctionsInDir(functionsDir)
  if (fns.length === 0) return null

  const supatypeDir = pathResolve(cwd, ".supatype")
  mkdirSync(supatypeDir, { recursive: true })
  const routerPath = join(supatypeDir, "functions-router.ts")
  const src = generateFunctionsRouterSource(routerPath, fns, devServiceRoleKeyPath(cwd))
  writeFileSync(routerPath, src, "utf8")
  return routerPath
}
