/**
 * The client a project imports, generated into its own source tree.
 *
 * One file, written by `supatype push`, that an app imports once:
 *
 *     import { createClient } from "./supatype/generated/client"
 *
 * It carries three things that used to arrive by three routes, two of which could fail without
 * saying so.
 *
 * The **module augmentation** was a `.d.ts` that TypeScript found only because the project's
 * tsconfig `include` happened to name the generated directory. Thirteen tsconfig files across the
 * examples named it, one project never named it at all, and in that state `AugmentedTables` falls
 * back to `Record<string, TableDef>`: every table name is accepted, every column is `unknown`, and
 * the build passes. Reaching it by import instead means tsconfig cannot lose it.
 *
 * The **field kinds** were read from `field-kinds.json` on disk, falling back to fetching
 * PostgREST's OpenAPI document. That fallback reconstructs the answer from the live database, so it
 * always succeeds, which made a project that had never generated indistinguishable from one that
 * had. Compiling them in removes both the read and the fallback, and makes absence detectable.
 *
 * And **`createClient`** itself, so the one import is the whole setup. A project that has not
 * generated has no file here to import, so the build fails rather than the app running with a
 * client that knows nothing about its schema.
 */
import { generateClientAugmentation, resolveTableName } from "./augmentation-generator.js"
import { astModels, objectAt } from "./ast-read.js"
import { keepsDrafts } from "./model-versioning.js"

/** The kinds whose values no binary float holds, keyed by the schema kind that produces them. */
const EXACT_KIND_BY_FIELD_KIND: Readonly<Record<string, "bigint" | "numeric">> = {
  bigInt: "bigint",
  bigSerial: "bigint",
  decimal: "numeric",
  money: "numeric",
}

const FORMAT_VERSION = 1

/**
 * The full contents of the project's `client.ts`. `importPath` is the specifier, from the project
 * root, its header tells an app to import, so it must name where the file is written.
 */
export function generateProjectClient(ast: unknown, importPath = "./supatype/generated/client"): string {
  // Normalised first: `push` should not die on a malformed AST while writing a file, and the
  // augmentation generator indexes `.models` without checking.
  const safe = ast !== null && typeof ast === "object" ? ast : { models: [] }
  const augmentation = generateClientAugmentation(safe)

  return [
    "// Generated by supatype CLI, do not edit manually.",
    "//",
    "// Import the client from here rather than from `@supatype/client`:",
    "//",
    `//     import { createClient } from "${importPath}"`,
    "//",
    "// This file carries your schema's types and the columns that need exact handling, so one",
    "// import is the whole setup. Importing `@supatype/client` directly gets a client that knows",
    "// nothing about this project.",
    "",
    'import { registerDraftModels, registerFieldKinds } from "@supatype/client"',
    "",
    augmentationBody(augmentation),
    "",
    "// Columns holding values a JSON parser would round: bigInt, decimal and money. Registered at",
    "// import time, so reading one returns what the database holds rather than the nearest double.",
    `registerFieldKinds(${JSON.stringify(fieldKindsDocument(safe), null, 2)})`,
    "",
    "// Models that keep drafts. An insert into one goes through `supatype.create_record`, or",
    "// `supatype.create_records` for several rows, which create each record as its first draft: a plain",
    "// insert asking for the row back is refused by a read rule that hides unpublished records.",
    `registerDraftModels(${JSON.stringify(draftModelsDocument(safe), null, 2)})`,
    "",
    'export * from "@supatype/client"',
    "",
  ].join("\n")
}

/**
 * The augmentation, without the pieces that only made sense in a file of its own.
 *
 * Its header said "generated", which this file says once already, and it ended in `export {}` to
 * make itself a module. This file has imports and exports of its own, so it is one regardless.
 */
function augmentationBody(augmentation: string): string {
  return augmentation
    .replace(/^\/\/ Generated by supatype CLI[^\n]*\n+/, "")
    .replace(/\n*export \{\}\s*$/, "")
    .trimEnd()
}

/** The exact-value columns of every table, as the registry expects them. */
function fieldKindsDocument(ast: unknown): { version: number; tables: Record<string, unknown> } {
  const tables: Record<string, Record<string, string>> = {}

  for (const model of astModels(ast)) {
    const exact: Record<string, string> = {}
    for (const [column, meta] of Object.entries(objectAt(model, "fields") ?? {})) {
      const kind = objectAt(meta)?.["kind"]
      const exactKind = typeof kind === "string" ? EXACT_KIND_BY_FIELD_KIND[kind] : undefined
      if (exactKind !== undefined) exact[column] = exactKind
    }
    if (Object.keys(exact).length > 0) {
      tables[resolveTableName(model)] = exact
    }
  }

  return { version: FORMAT_VERSION, tables }
}

/** Every model that keeps drafts, by table, with the key its new records are read back through. */
function draftModelsDocument(ast: unknown): { version: number; tables: Record<string, { primaryKey: string }> } {
  const tables: Record<string, { primaryKey: string }> = {}
  for (const model of astModels(ast)) {
    if (!keepsDrafts(model)) continue
    tables[resolveTableName(model)] = { primaryKey: primaryKeyColumn(objectAt(model, "fields")) }
  }
  return { version: FORMAT_VERSION, tables }
}

/** The field marked as the key, else `id`, which is what the engine keys a model by when none is. */
function primaryKeyColumn(fields: Record<string, unknown> | undefined): string {
  const keyed = Object.entries(fields ?? {}).find(([, meta]) => objectAt(meta)?.["primaryKey"] === true)
  return keyed?.[0] ?? "id"
}
